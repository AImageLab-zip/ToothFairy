def _quote_tags(tags):
    """\"'a', 'b' and 'c'\" -- panel tags as they appear in caption prose."""
    quoted = [f"'{t}'" for t in tags]
    if len(quoted) == 1:
        return quoted[0]
    return ", ".join(quoted[:-1]) + f" and {quoted[-1]}"


def build_tooth_static_caption(fdi):
    """
    Static description of a tooth composite -- what the image shows, no case
    findings. Identical for every tooth bar two things that follow from the
    FDI alone: the surface names (from the tooth's quadrant and whether it is
    anterior or posterior) and the mandibular-canal sentence, which is written
    for lower teeth only because the canal is drawn on lower composites only.

    Nothing drawn on the image names a tooth SURFACE: the markers and the
    panel tags are patient directions ("L" = the patient's left, "P" =
    posterior, sagittal cuts tagged right/mid/left). Surfaces are spoken here
    instead, because which surface a patient direction lands on is per-tooth
    -- it depends on the quadrant AND on whether the tooth is anterior.
    """
    right_quadrant = (11 <= fdi <= 18 or 41 <= fdi <= 48)
    anterior       = (fdi % 10) <= 3          # FDI position 1-3: incisors, canine

    # The two surfaces at the ends of the medio-lateral axis, patient's-right
    # end first. That one pair serves both rows whose horizontal axis is X:
    # the flip puts the patient's right on the image's LEFT, so `near` is the
    # left edge of every axial and coronal panel, and it is also where the
    # sagittal row starts, since that row steps right -> left.
    #
    # A right-quadrant tooth meets its own (buccal/labial) side first, a
    # left-quadrant tooth meets it last. For an anterior tooth the same sweep
    # crosses mesial-distal instead -- an incisor's labial surface faces
    # forward, not sideways -- and mesial is the side facing the midline, so a
    # right-quadrant incisor runs distal -> mesial.
    if anterior:
        near, far = ("distal", "mesial") if right_quadrant else ("mesial", "distal")
    else:
        near, far = ("buccal", "lingual") if right_quadrant else ("lingual", "buccal")

    parts = [TOOTH_STATIC_CAPTION_INTRO.format(fdi=fdi)]
    if fdi in _LOWER_TIDS:
        parts.append(TOOTH_CANAL_CAPTION.format(fdi=fdi, colour=CANAL_COLOR_NAME))
    return " ".join(parts + [
        "Top row: " + _TOOTH_AXIAL_TEXT.format(tags=_quote_tags(_AXIAL_TAGS)) + ".",
        "Middle row: " + _TOOTH_CORONAL_TEXT.format(
            tags=_quote_tags(_CORONAL_TAGS), fdi=fdi,
            near_surface=near, far_surface=far) + ".",
        "Bottom row: " + _TOOTH_SAGITTAL_TEXT.format(
            tags=_quote_tags(_SAGITTAL_TAGS),
            near_surface=near, far_surface=far) + ".",
    ])


def build_tooth_fact_fragments(fdi, facts):
    """
    Terse fragments for whichever of the six in-scope case-level fields
    actually name this FDI. Returns [] for an empty/missing facts dict.
    """
    structured = facts.get("structured", {})

    fragments = []
    if fdi in _normalize_fdi_list(structured.get("teeth_absent")):
        fragments.append(f"Tooth {fdi} listed absent in this case's findings.")
    if fdi in _normalize_fdi_list(structured.get("crowns")):
        fragments.append(f"Tooth {fdi} crown.")
    if fdi in _normalize_fdi_list(structured.get("implants")):
        fragments.append(f"Tooth {fdi} endosseous implant.")
    for start, end in _normalize_bridge_spans(structured):
        if fdi in (start, end):
            fragments.append(f"Tooth {fdi} part of {start}-{end} fixed bridge.")
    if fdi in _normalize_fdi_list(structured.get("ian_close_teeth")):
        fragments.append(f"Tooth {fdi} close to mandibular canal.")
    return fragments


def build_tooth_caption(fdi, facts):
    """
    Static layout description plus any in-scope facts naming this tooth.
    An empty facts dict returns just the static description.
    """
    parts = [build_tooth_static_caption(fdi)]
    parts.extend(build_tooth_fact_fragments(fdi, facts))
    return " ".join(parts)



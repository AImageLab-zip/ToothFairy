# ── Text ──────────────────────────────────────────────────────────────────────
#
# PIL's built-in bitmap font is ~11 px tall and cannot be scaled on older
# Pillow builds, which is why every label on this composite used to be
# unreadable next to a 1344-px canvas. A real TrueType face is loaded instead
# so label sizes can scale with the canvas; the bitmap font stays as a
# last-resort fallback so a machine without DejaVu still renders something.

_FONT_PATHS = {
    False: ("/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",),
    True:  ("/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",),
}
_FONT_CACHE = {}


def _font(size, bold=False):
    """A scalable font at `size` px, cached; bitmap default if none is found."""
    key = (int(size), bool(bold))
    if key in _FONT_CACHE:
        return _FONT_CACHE[key]
    from PIL import ImageFont
    font = None
    for path in _FONT_PATHS[bool(bold)] + _FONT_PATHS[False]:
        try:
            font = ImageFont.truetype(path, int(size))
            break
        except OSError:
            continue
    if font is None:
        try:               font = ImageFont.load_default(size=int(size))
        except TypeError:  font = ImageFont.load_default()
    _FONT_CACHE[key] = font
    return font


def _text_size(draw, text, font):
    """(w, h) of `text` in `font`, measured rather than guessed at 7 px/char."""
    x0, y0, x1, y1 = draw.textbbox((0, 0), text, font=font)
    return x1 - x0, y1 - y0


def _vlabel(canvas, box, text, font, color=(235, 235, 235)):
    """
    Paste `text` rotated 90° CCW (reading bottom-to-top), centred in `box`.

    Drawn on its own horizontal strip and rotated, because PIL cannot draw
    rotated text directly. The strip is the box with its axes swapped, so the
    rotation lands exactly on the box with no resampling of the glyphs.
    """
    x, y, w, h = box
    strip = Image.new("RGB", (max(1, h), max(1, w)), (0, 0, 0))
    d     = ImageDraw.Draw(strip)
    x0, y0, x1, y1 = d.textbbox((0, 0), text, font=font)
    d.text(((h - (x1 - x0)) // 2 - x0, (w - (y1 - y0)) // 2 - y0),
           text, fill=color, font=font)
    canvas.paste(strip.rotate(90, expand=True), (x, y))


# ── Windowing ─────────────────────────────────────────────────────────────────

def _window(arr, lo_pct=0.5, hi_pct=99.5):
    """Compute percentile window from arr itself (for full-slice axial)."""
    lo  = np.percentile(arr, lo_pct)
    hi  = np.percentile(arr, hi_pct)
    out = np.clip((arr - lo) / max(hi - lo, 1e-6), 0.0, 1.0)
    return (out * 255).astype(np.uint8)


def _apply_window(arr, lo_val, hi_val):
    """Apply pre-computed window bounds — never recompute on a small crop."""
    out = np.clip((arr.astype(np.float32) - lo_val) / max(hi_val - lo_val, 1e-6), 0., 1.)
    return (out * 255).astype(np.uint8)


def _resolve_window(volume, window_center, window_width, lo_pct, hi_pct):
    """
    Decide the (lo_val, hi_val) grey-level bounds for one case.

    Fixed HU window when window_center/window_width are given (the default --
    see DEFAULT_WINDOW_CENTER); percentiles of this volume when they are not.
    Percentile mode is kept only as an escape hatch for volumes that are not
    HU-calibrated, where a fixed window means nothing; it is the mode that
    made brightness drift between cases and clipped enamel to white.
    """
    if window_center is not None and window_width is not None:
        return (float(window_center) - float(window_width) / 2.0,
                float(window_center) + float(window_width) / 2.0)
    return (float(np.percentile(volume, lo_pct)),
            float(np.percentile(volume, hi_pct)))


def _crop2d(arr, r0, r1, c0, c1, fill):
    """
    Crop arr[r0:r1+1, c0:c1+1], allowing the window to run off any edge.

    The out-of-volume part is filled with `fill` rather than the window being
    slid back inside, so a tooth near the edge of the FOV still sits in the
    centre of its own tile.
    """
    out = np.full((r1 - r0 + 1, c1 - c0 + 1), fill, dtype=arr.dtype)
    sr0, sr1 = max(r0, 0), min(r1, arr.shape[0] - 1)
    sc0, sc1 = max(c0, 0), min(c1, arr.shape[1] - 1)
    if sr0 <= sr1 and sc0 <= sc1:
        out[sr0-r0:sr1-r0+1, sc0-c0:sc1-c0+1] = arr[sr0:sr1+1, sc0:sc1+1]
    return out


def _tooth_outline_2d(tooth_2d, bridge=4, width=2):
    """
    Return an outer border mask, `width` voxels thick, for a 2D tooth slice.

    Used for the target tooth. The mandibular canal is painted solid instead
    (see _canal_region in make_tooth_composite), so this stays what it always
    was: the tooth's border, keeping its interior visible.

    Multi-root molars appear as separate blobs at the root level. We bridge
    the gap between roots with morphological closing (dilation → erosion),
    fill any interior holes, then extract the outer boundary.

    The border is thickened INWARD (erode further, subtract) rather than by
    dilating outward, so a thicker line never grows the tooth's apparent
    silhouette -- the outline still traces the segmentation boundary exactly,
    it just paints more pixels of the tooth's own edge. Growing outward would
    creep over the neighbouring tooth's enamel on a tight contact.

    Parameters
    ----------
    tooth_2d : (H, W) bool  — tooth voxels in one 2D slice
    bridge   : closing radius in voxels (default 4 — bridges root gaps)
    width    : border thickness in voxels (1 = the old hairline)
    """
    from scipy.ndimage import binary_erosion, binary_dilation, binary_fill_holes
    if not tooth_2d.any():
        return np.zeros_like(tooth_2d, dtype=bool)
    # Closing = dilate then erode: bridges small gaps without expanding the shape much
    merged = binary_erosion(binary_dilation(tooth_2d, iterations=bridge),
                            iterations=bridge)
    # Fill enclosed holes (e.g. pulp cavity gaps)
    filled = binary_fill_holes(merged)
    inner = binary_erosion(filled, iterations=max(1, int(width)))
    if not inner.any():          # tiny structure -- keep the hairline rather
        inner = binary_erosion(filled)   # than painting the whole thing solid
    return filled & ~inner



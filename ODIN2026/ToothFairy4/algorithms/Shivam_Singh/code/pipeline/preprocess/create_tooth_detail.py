    ap.add_argument("--out-w",      type=int, default=1344,
                    help="Canvas width; the height follows from it (3 equal "
                         "columns, tiles at the window's own aspect)")
    ap.add_argument("--out-h",      type=int, default=None,
                    help=argparse.SUPPRESS)   # ignored: height is derived
    ap.add_argument("--limit",      type=int, default=None,
                    help="Max cases in batch mode")
    args = ap.parse_args()

    # --window-percentile is the opt-out: passing None for both bounds is what
    # _resolve_window reads as "fall back to percentiles".
    wc = None if args.window_percentile else args.window_center
    ww = None if args.window_percentile else args.window_width

    if args.volume:
        if not args.mask:
            ap.error("--mask is required with --volume")
        cid = args.case_id or _case_id_from_path(args.mask)
        process_case(args.volume, args.mask, args.out_dir, cid,
                     fdi_filter=args.fdi, out_w=args.out_w,
                     window_scale=args.window_scale,
                     window_center=wc, window_width=ww,
                     facts_path=args.facts_file)

# ── Shared RAS+ loading (used by both create_tooth_detail.py and
#    create_tooth_apex_composite.py -- kept in exactly ONE place so the two
#    scripts' orientation handling can't silently drift apart) ──────────────

def load_as_ras(vol_path, mask_path):
    """
    Reorient volume and mask to RAS+ using the SAME transform.

    Why same transform:
      If computed independently, float-precision differences in the two
      affines can produce different ornt_transform results, causing the
      volume and mask to end up in different orientations (sagittal mismatch).
      Using the volume affine for both guarantees they are always aligned.

    LPS (common CBCT/DICOM convention) → RAS+:
      axis 0 L→R  (flip),  axis 1 P→A  (flip),  axis 2 S stays
    Any other input orientation is handled the same way.
    """
    import nibabel as nib
    import nibabel.orientations as nibo

    vol_nib  = nib.load(str(vol_path))
    mask_nib = nib.load(str(mask_path))

    # Derive transform from VOLUME affine only
    ornt = nibo.io_orientation(vol_nib.affine)
    ras  = nibo.axcodes2ornt(('R', 'A', 'S'))
    xfm  = nibo.ornt_transform(ornt, ras)

    print(f"  input orientation: {nibo.ornt2axcodes(ornt)} → RAS+", file=sys.stderr)

    return vol_nib.as_reoriented(xfm), mask_nib.as_reoriented(xfm)


def process_case(volume_path, mask_path, out_dir, case_id,
                 fdi_filter=None, out_w=1344, window_scale=DEFAULT_WINDOW_SCALE,
                 window_center=DEFAULT_WINDOW_CENTER,
                 window_width=DEFAULT_WINDOW_WIDTH,
                 facts_path=None):
    """
    Generate one composite image per detected tooth for a single case.
    Output: {out_dir}/{case_id}_tooth{FDI}_composite.png, plus one
    {out_dir}/{case_id}_tooth_captions.json sidecar keyed by
    "tooth_{fdi}_composite" (schema.json's images_needed key format).

    Nothing outside the volume/mask is read: the composite is nine slices of
    this case's own scan, so it no longer depends on the panoramic or the 3D
    renders having been generated first.

    `facts_path` is optional. When given, the case findings that name a
    given tooth are appended to that tooth's caption at generation time
    (see build_tooth_caption); without it every caption is the static
    layout description alone, which is still correct — just less specific.
    """
    print(f"[{case_id}] loading ...", file=sys.stderr)

    vol_nib, mask_nib = load_as_ras(volume_path, mask_path)
    # Plain get_fdata() materialises AND caches a float64 copy of each volume
    # before the downcast, so a 562³ case peaked around 6.7 GB and was
    # OOM-killed before writing a single composite. Asking for float32
    # directly, and reading the mask straight off dataobj in its stored
    # integer dtype, keeps the same arrays at roughly a third of that.
    volume   = vol_nib.get_fdata(dtype=np.float32)
    mask     = np.asanyarray(mask_nib.dataobj).astype(np.int32, copy=False)
    spacing  = float(np.mean(vol_nib.header.get_zooms()[:3]))
    print(f"  spacing: {spacing:.3f} mm  shape: {'×'.join(str(s) for s in volume.shape)}",
          file=sys.stderr)

    # Log the resolved grey-level window. Worth printing per case: it is the
    # single number that decides whether enamel and dental material come out
    # as different greys, and in percentile mode it silently differs per case.
    _lo, _hi = _resolve_window(volume, window_center, window_width, 0.5, 99.5)
    _mode = "fixed HU" if window_center is not None and window_width is not None \
            else "percentile"
    print(f"  grey window ({_mode}): [{_lo:.0f}, {_hi:.0f}] HU", file=sys.stderr)

    # Diagnostic: show which tooth train-IDs are actually present in the mask
    present_ids = sorted(v for v in np.unique(mask) if v > 10)
    print(f"  mask labels present (>10): {present_ids}", file=sys.stderr)
    expected_ids = sorted(_TEETH_IDS)
    missing_ids  = sorted(set(expected_ids) - set(present_ids))
    if missing_ids:
        print(f"  [warn] expected train IDs not in mask: {missing_ids}", file=sys.stderr)

    # Laterality FIRST, from the mask itself — every B/L and L/R marker
    # below depends on it, and this dataset contradicts its own affine.
    right_low_x = detect_right_low_x(mask)
    if right_low_x is None:
        right_low_x = True     # neither side anchorable — dataset default
        print("  [warn] laterality undetermined from mask — assuming patient "
              "RIGHT at low X", file=sys.stderr)
    else:
        print(f"  patient RIGHT is at {'LOW' if right_low_x else 'HIGH'} X "
              "(from mask)", file=sys.stderr)

    os.makedirs(out_dir, exist_ok=True)

    facts = load_case_facts(facts_path)

    all_fdis = (list(range(11,19)) + list(range(21,29)) +
                list(range(31,39)) + list(range(41,49)))
    fdis  = fdi_filter if fdi_filter else all_fdis

    # ── An excluded maxilla gets no upper composites ──────────────────────
    #
    # A composite is nine crops built around a tooth's own extent, and the
    # three "root" panels are the point of it. When the volume stops above
    # the occlusal plane there is no root to crop: S0027's tooth 16 renders
    # as a red dot at the top edge with a blank axial-root panel, and its
    # crown/caries/filling questions are unanswerable from it.
    #
    # Measured on all 622 cases -- of the 256 whose maxillary bone is out of
    # the volume but whose upper teeth are still labelled, 87.1% of reference
    # reports say nothing whatever about an upper tooth (vs 42.5% when the
    # maxilla IS imaged). The 11.7% that do describe one describe a CROWN
    # ("as far as can be visualized, prosthetic crowns are present on teeth
    # 14, 13, 12..."), which the panoramic arch read still sees --
    # dental_arch_findings_maxilla is deliberately kept for exactly that.
    #
    # This is also free: postprocess_pred.drop_excluded_maxilla already
    # discards every tooth_11..28 read for a not_included maxilla, so these
    # composites were rendered, sent to the VLM, and then thrown away. 5,440
    # calls on the training split, 41% of that group's total.
    coverage = arch_coverage(mask_label_volumes(mask, mask_nib.header.get_zooms()))
    maxilla_imaged = coverage["maxilla"]["bone"]
    if not maxilla_imaged:
        before = len(fdis)
        fdis = [f for f in fdis if f not in MAXILLA_FDIS]
        print(f"  maxilla not in the volume ({MIN_ARCH_BONE_MM3:.0f} mm^3 "
              f"threshold) — skipping {before - len(fdis)} upper composite(s)",
              file=sys.stderr)
    saved = []
    captions = {}

    for fdi in fdis:
        img = make_tooth_composite(volume, mask, tooth_tid=fdi, fdi=fdi,
                                   window_scale=window_scale,
                                   window_center=window_center,
                                   window_width=window_width,
                                   right_low_x=right_low_x,
                                   spacing_mm=spacing, out_w=out_w)
        if img is None:
            print(f"  FDI {fdi:2d}: not found — skipped", file=sys.stderr)
            continue
        out_path = os.path.join(out_dir, f"{case_id}_tooth{fdi}_composite.png")
        img.save(out_path)
        print(f"  FDI {fdi:2d} → {out_path}", file=sys.stderr)
        saved.append(out_path)

        # Caption written here rather than in a post-hoc pass, so the image
        # and the text describing it are produced by the same run.
        captions[f"tooth_{fdi}_composite"] = build_tooth_caption(fdi, facts)

    # ── Coverage sidecar ──────────────────────────────────────────────────
    #
    # The mask's verdict, written down so build_vqa_pairs.py can act on it.
    # That script has no mask -- it plans VLM calls from the images on disk --
    # and "no upper composites" alone cannot tell the two excluded cases
    # apart: 256 have upper teeth in the volume (the panoramic still shows
    # their crowns, so dental_arch_findings_maxilla is worth asking) and 98
    # have none at all (nothing to read, skip the call). One boolean each,
    # from the same arch_coverage every other stage uses.
    cov_path = os.path.join(out_dir, f"{case_id}_coverage.json")
    with open(cov_path, "w") as f:
        json.dump({arch: {k: bool(v) for k, v in vals.items()}
                   for arch, vals in coverage.items()}, f, indent=2)
    print(f"  coverage → {cov_path}", file=sys.stderr)

    n_images = len(saved)
    if captions:
        cap_path = os.path.join(out_dir, f"{case_id}_tooth_captions.json")
        with open(cap_path, "w") as f:
            json.dump(captions, f, indent=2)
        print(f"  captions → {cap_path}", file=sys.stderr)
        saved.append(cap_path)

    print(f"[{case_id}] done — {n_images} images saved.", file=sys.stderr)
    return saved


def _case_id_from_path(path):
    from pathlib import Path
    stem = Path(path).name
    for s in (".nii.gz", ".nii"):
        if stem.endswith(s):
            stem = stem[:-len(s)]
    return stem.replace("ToothFairy", "").replace("_0000", "")


def _find_volume(mask_path, volumes_dir):
    import glob
    stem = _case_id_from_path(mask_path)
    for pat in [f"*{stem}*.nii.gz", f"*{stem}*_0000.nii.gz"]:
        hits = sorted(glob.glob(os.path.join(volumes_dir, pat)))
        if hits:
            return hits[0]
    return None



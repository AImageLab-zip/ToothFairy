#!/usr/bin/env python3
"""
code/pipeline/preprocess/create_tooth_detail.py

Generate a multi-view CBCT composite image for each tooth in a case.

Layout — 3×3 grid, one plane per row, every cell the same size
──────────────────────────────────────────────────────────────

┌─────────────┬─────────────┬─────────────┐
│ AXIAL crown │  AXIAL mid  │  AXIAL root │  row 1  (Z-cuts, crown → apex)
├─────────────┼─────────────┼─────────────┤
│ CORONAL post│ CORONAL mid │ CORONAL ant │  row 2  (Y-cuts, P → A)
├─────────────┼─────────────┼─────────────┤
│  SAG right  │   SAG mid   │  SAG left   │  row 3  (X-cuts, patient R → L)
└─────────────┴─────────────┴─────────────┘

Every tile carries the target tooth outlined in red, and — on lower teeth —
the mandibular canal filled with a translucent yellow wash, the colour the 3D
renders already use for it (create_3d_renders.CANAL_COLOR). The canal is what the root-apex
panels are read against, so it is marked rather than left to be found; it is
filled rather than outlined because at these zoom levels its cross-section is
only a few pixels wide and nothing downstream asks what is inside it.

Every tile is centred on the tooth. The coronal and sagittal rows share one
window — the tooth plus the maxilla/mandible bone in its own column — at one
mm-per-pixel scale, so those two are directly comparable; that window is
CENTRED on the tooth and sized from its longer (root) side, so the bone past
the apex stays in frame and the crown gets the same clearance above it rather
than sitting on the tile border. The axial row is centred the same way but zoomed
in further (DEFAULT_AXIAL_SCALE), because an axial cut through a tooth is
about one tooth wide and the shared window is sized by the tooth's HEIGHT --
at the shared scale most of the axial tile was the opposite side of the arch.

There is no case-level context panel (panoramic / 3D render) any more: the
nine slice tiles fill the grid. The whole-arch panoramic and the 3D renders
are still generated by their own scripts and are still separate images in the
VQA set — they are simply not pasted into the tooth composite.

Output
──────
  {case_id}_tooth{FDI}_composite.png
  {case_id}_tooth_captions.json   -- {"tooth_16_composite": "<caption>", ...}

Each caption is written at generation time: a static description of the grid
(identical for every tooth now that the layout no longer varies), plus terse
fragments for any case finding in --facts-file that names that tooth. See the
Caption section below.

Usage
─────
  # Single case — all teeth
  python code/pipeline/preprocess/create_tooth_detail.py \
      --volume  dataset/validate/images/S0050_0000.nii.gz \
      --mask    dataset/validate/masks/S0050.nii.gz \
      --facts-file dataset/validate/facts/S0050.json \
      --out-dir     outputs/tooth_composite/ \
      --fdi 16

  # Specific teeth only
  python code/pipeline/preprocess/create_tooth_detail.py ... --fdi 16 46

  # Batch with limit
  python code/pipeline/preprocess/create_tooth_detail.py \
      --volumes-dir dataset/images/ \
      --masks-dir   dataset/predictions/ \
      --out-dir     outputs/tooth_composite/ --limit 5
"""


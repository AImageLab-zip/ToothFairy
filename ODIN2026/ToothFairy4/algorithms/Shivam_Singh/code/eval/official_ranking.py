def print_progress(batch_num: int, n_batches: int, agg: dict) -> None:
    stats = agg.get("per_case_stats", {})
    print(f"\n[BATCH {batch_num}/{n_batches}] Rolling aggregate so far "
          f"({agg['num_cases']} case(s)):", file=sys.stderr)
    print(f"  BLEU-4: {agg['bleu_4']:.4f}  METEOR: {agg['meteor']:.4f}  "
          f"Captioning: {agg['captioning_score']:.4f}", file=sys.stderr)
    if agg["radfact_enabled"]:
        print(f"  RadFact P/R: {agg['logical_precision']:.4f}/{agg['logical_recall']:.4f}  "
              f"Clinical: {agg['clinical_score']:.4f}", file=sys.stderr)
    print(f"  Final Score: {agg['final_score']:.4f}", file=sys.stderr)
    if stats:
        fs = stats.get("final_score", {})
        cs = stats.get("clinical_score", {})
        print(f"  Per-case: Final {fs.get('mean', 0):.4f} +/- {fs.get('sd', 0):.4f}  "
              f"Clinical {cs.get('mean', 0):.4f} +/- {cs.get('sd', 0):.4f}", file=sys.stderr)


def print_summary(agg: dict) -> None:
    stats = agg.get("per_case_stats", {})
    print("\n" + "=" * 70, file=sys.stderr)
    print("OFFICIAL RANKING SUMMARY (Phase 1 - Automatic Ranking)", file=sys.stderr)
    print("=" * 70, file=sys.stderr)
    print(f"Cases evaluated: {agg['num_cases']}", file=sys.stderr)
    print(f"BLEU-4:  {agg['bleu_4']:.4f}", file=sys.stderr)
    print(f"METEOR:  {agg['meteor']:.4f}", file=sys.stderr)
    print(f"Captioning Score (mean of BLEU-4, METEOR): {agg['captioning_score']:.4f}",
          file=sys.stderr)
    if agg["radfact_enabled"]:
        print(f"RadFact Logical Precision: {agg['logical_precision']:.4f}", file=sys.stderr)
        print(f"RadFact Logical Recall:    {agg['logical_recall']:.4f}", file=sys.stderr)
        print(f"Clinical Score (RadFact Logical F1): {agg['clinical_score']:.4f}",
              file=sys.stderr)
    else:
        print("RadFact: NOT computed (Clinical Score = 0.0)", file=sys.stderr)
    print(f"\nFINAL SCORE = 0.8 * Clinical + 0.2 * Captioning = {agg['final_score']:.4f}",
          file=sys.stderr)

    if stats:
        print("\n--- Per-case mean +/- sd (official numbers above are corpus-level, not this) ---",
              file=sys.stderr)
        for key in ("bleu_4", "meteor", "captioning_score", "logical_precision",
                    "logical_recall", "logical_f1", "clinical_score", "final_score"):
            if key in stats:
                s = stats[key]
                print(f"  {key}: {s['mean']:.4f} +/- {s['sd']:.4f}", file=sys.stderr)
    print("=" * 70 + "\n", file=sys.stderr)



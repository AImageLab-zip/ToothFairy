#!/usr/bin/env python3
"""
code/eval/official_ranking.py

Phase 1 - Automatic Ranking, per the official ODIN2026/ToothFairy4 rules:

  Clinical Score  = RadFact Logical F1 (harmonic mean of RadFact Logical
                    Precision and RadFact Logical Recall)
  Captioning Score = mean(BLEU-4, METEOR)
  Final Score      = 0.8 * Clinical Score + 0.2 * Captioning Score

BLEU-4 / METEOR (tokenize, bleu_4_local, meteor_lite_score, has_wordnet) are
adapted from the official AImageLab-zip/ToothFairy evaluate.py
(ODIN2026/ToothFairy4/evaluation/evaluate.py, MIT License) to guarantee
scoring parity with the real challenge.

RadFact is computed via the official `radfact_lite` PyPI package
(ReportType.TOOTHFAIRY prompts). The judge LLM behind it is selectable with
--judge-backend:

  vllm   (default) -- a LOCAL vLLM server. radfact_lite's ModelConfig
                      supports provider="openai" with a custom base_url,
                      and vLLM's OpenAI-compatible server accepts the same
                      request shape (structured JSON-schema output).
  openai           -- the real OpenAI API (api.openai.com), keyed from
                      $OPENAI_API_KEY. This is what the original RadFact
                      paper used, so it is the closer match to the
                      challenge's own scoring, but it costs money: the
                      pipeline is serial and issues roughly one chat
                      completion per phrase per report (parse + entailment
                      both ways), i.e. tens of calls per case.

Both paths go through the same radfact_lite code; only the ModelConfig
differs, so scores are directly comparable modulo the judge model itself.

Three things make a score non-comparable across runs, so all three are
recorded into summary.json rather than assumed. The first is METEOR's; the
other two are radfact_lite's:

  meteor_backend -- "nltk-wordnet" or "lite-fallback". nltk ships no corpora,
                    so a clean env has no wordnet and METEOR silently drops to
                    the lite implementation, on a different scale. Install it
                    with `python -m nltk.downloader wordnet omw-1.4`; every
                    number in this repo is "nltk-wordnet".
  filter_normal_findings  -- ON by default. radfact_lite's finding filter runs
                    over both candidate and reference phrases before
                    entailment, so normal/boilerplate statements ("all other
                    teeth are present", "the canal has a regular course") do
                    not prop up precision and recall on both sides. Disable
                    with --no-filter-normal-findings.
  radfact_lite_prompts -- upstream rewrote the TOOTHFAIRY parse / entailment /
                    filter prompts on 2026-08-09 (one phrase per tooth in a
                    tooth list; exact tooth-number matching for entailment; a
                    four-case normal-vs-abnormal taxonomy for the filter).
                    PyPI still ships the pre-rewrite build as 0.1.0, so an
                    ordinary `pip install radfact-lite` yields the "legacy"
                    prompts; "2026-08-09+" means the git version is installed.

Candidate reports are read directly from pre-synthesized .txt files
(generated by synthesize_report.py --prediction <pred_dir> --out-dir <synth_dir>).
Missing synthesized reports -> empty string, matching official "missing result"
semantics.

INCREMENTAL EVALUATION: cases are processed in batches (--batch-size,
default 10). Each batch's per-case results are appended to results.jsonl
immediately after that batch completes -- not held in memory until the
whole run finishes -- so a crash/timeout partway through a large run loses
at most one batch, not everything. A rolling summary.json is rewritten
after every batch from ALL rows processed so far (this run plus any
--resume'd prior rows). A final timestamped official_ranking_<timestamp>.json
is also written once the whole run completes.

Usage:
  # Local Qwen3 judge via vLLM (default, unchanged behavior):
  python3 code/eval/official_ranking.py \
      --schema schema/schema.json \
      --synthesized-dir test_5/outputs/synthesized_reports \
      --reports-dir test_5/dataset/reports \
      --out-dir test_5/outputs/official_ranking \
      --vllm-url http://localhost:8001/v1 \
      --model qwen3-14b-text \
      --batch-size 10 \
      --resume

  # OpenAI judge (needs OPENAI_API_KEY in the environment; no GPU/vLLM):
  python3 code/eval/official_ranking.py \
      --schema schema/schema.json \
      --synthesized-dir outputs/aksssr_v4_validate/synthesized_reports \
      --reports-dir test_5/dataset/reports \
      --out-dir dataset/validate/reports \
      --judge-backend openai \
      --openai-model gpt-4o

  # Skip RadFact (e.g. if the vLLM structured-output call fails), BLEU/METEOR only:
  python3 code/eval/official_ranking.py ... --no-radfact
"""

import json
import os
import re
import sys
import argparse
import statistics
from pathlib import Path
from datetime import datetime
from typing import Dict, List, Optional, Tuple



# ── Reference report lookup ───────────────────────────────────────────────

def find_all_reference_reports(reports_dir: Path, case_id: str) -> List[Path]:
    """
    EVERY reference .txt report for a case, in stable order. Handles:
      - {case_id}.txt
      - {case_id}_1.txt, {case_id}_2.txt, ...   (one per radiologist)
      - {case_id}_report.txt

    59.7% of this dataset's cases (348/583) carry more than one report --
    two independent radiologists describing the same scan. The [0] element
    is the PRIMARY reference: it is what single-reference scoring uses, and
    what RadFact always uses (RadFact has no multi-reference mode).
    """
    exact = reports_dir / f"{case_id}.txt"
    if exact.exists():
        return [exact]
    return sorted(reports_dir.glob(f"{case_id}_*.txt"))


def find_first_reference_report(reports_dir: Path, case_id: str) -> Optional[Path]:
    """Primary reference only -- kept for callers that want exactly one."""
    found = find_all_reference_reports(reports_dir, case_id)
    return found[0] if found else None


# ── BLEU-4 / METEOR ──────────────────────────────────────────────────────
# Adapted from AImageLab-zip/ToothFairy ODIN2026/ToothFairy4/evaluation/evaluate.py (MIT License)

WORDNET_AVAILABLE: Optional[bool] = None

# The wordnet corpus is DATA, not a pip dependency: `pip install nltk` gives
# you the code and none of the corpora, and nltk's own answer to a missing one
# is a LookupError at first use. So this file has two METEOR implementations
# and picks between them at run time -- which means a clean rebuild of the env
# silently scores METEOR on a different scale than every number in this repo
# (METEOR is half the captioning score, i.e. 10% of the Final Score).
#
# Two guards, because the fallback is legitimate (it is the official
# evaluate.py's own) and the silence is not:
#   1. has_wordnet() says so, once, loudly, with the fix.
#   2. meteor_backend() goes into summary.json next to judge_model and
#      radfact_lite_prompts, so which one ran is recorded per run rather
#      than inferred from when the env was built.
WORDNET_HINT = ("METEOR is running on the lite fallback, NOT nltk+wordnet. "
                "The two do not score the same. Install the corpus with:\n"
                "[WARN]   python -m nltk.downloader wordnet omw-1.4")


def tokenize(text: str) -> List[str]:
    return [token for token in re.findall(r"\w+|[^\w\s]", text.lower()) if token.strip()]


def has_wordnet() -> bool:
    global WORDNET_AVAILABLE
    if WORDNET_AVAILABLE is not None:
        return WORDNET_AVAILABLE
    try:
        from nltk.corpus import wordnet
        wordnet.ensure_loaded()
        WORDNET_AVAILABLE = True
    except LookupError:
        WORDNET_AVAILABLE = False
        print(f"[WARN] {WORDNET_HINT}", file=sys.stderr)
    return WORDNET_AVAILABLE


def meteor_backend() -> str:
    """Which METEOR implementation this run used. Recorded as provenance."""
    return "nltk-wordnet" if has_wordnet() else "lite-fallback"


def _as_reference_list(reference) -> List[str]:
    """Accept either one reference string or a list of them, always return a
    list. Lets every caller pass whichever it has without a shape change."""
    if isinstance(reference, str):
        return [reference]
    return [r for r in reference if r]


def bleu_4_local(predictions: List[str], references: List) -> float:
    """
    references[i] is either a single reference string or a LIST of reference
    strings for prediction i. With several, this is standard multi-reference
    BLEU: corpus_bleu takes the MAX n-gram count across references, so a
    candidate matching any one radiologist's phrasing gets credit.
    """
    from nltk.translate.bleu_score import SmoothingFunction, corpus_bleu

    predicted_tokens = [tokenize(p) for p in predictions]
    reference_tokens = [[tokenize(r) for r in _as_reference_list(refs)]
                        for refs in references]
    if not predicted_tokens:
        return 0.0

    return float(
        corpus_bleu(
            list_of_references=reference_tokens,
            hypotheses=predicted_tokens,
            weights=(0.25, 0.25, 0.25, 0.25),
            smoothing_function=SmoothingFunction().method1,
        )
    )


def greedy_match_indices(prediction_tokens: List[str], reference_tokens: List[str]) -> List[int]:
    used = [False] * len(reference_tokens)
    indices: List[int] = []
    for token in prediction_tokens:
        for index, ref_token in enumerate(reference_tokens):
            if used[index] or token != ref_token:
                continue
            used[index] = True
            indices.append(index)
            break
    return indices


def chunk_count(indices: List[int]) -> int:
    if not indices:
        return 0
    chunks = 1
    for current, previous in zip(indices[1:], indices[:-1]):
        if current != previous + 1:
            chunks += 1
    return chunks


def meteor_lite_score(prediction_tokens: List[str], reference_tokens: List[str]) -> float:
    matched = greedy_match_indices(prediction_tokens, reference_tokens)
    matches = len(matched)
    if matches == 0:
        return 0.0
    precision = matches / len(prediction_tokens)
    recall = matches / len(reference_tokens)
    denominator = recall + 9.0 * precision
    if denominator == 0.0:
        return 0.0
    f_mean = (10.0 * precision * recall) / denominator
    chunks = chunk_count(matched)
    penalty = 0.5 * (chunks / matches) ** 3
    return float((1.0 - penalty) * f_mean)


def meteor_batch(predictions: List[str], references: List) -> float:
    """
    references[i] is a single reference string or a LIST of them. With several,
    the case scores as the BEST match across references -- METEOR's own
    multi-reference convention, and the same "credit any valid phrasing" rule
    multi-reference BLEU applies.

    nltk's meteor_score already takes a list of references and maximises over
    them internally; the lite fallback maximises here.
    """
    if not predictions:
        return 0.0

    use_wn = has_wordnet()
    scores = []
    if use_wn:
        from nltk.translate.meteor_score import meteor_score as nltk_meteor_score

    for prediction, refs in zip(predictions, references):
        p_tok = tokenize(prediction)
        r_toks = [tokenize(r) for r in _as_reference_list(refs)]
        r_toks = [r for r in r_toks if r]
        if not p_tok and not r_toks:
            scores.append(1.0)
            continue
        if not p_tok or not r_toks:
            scores.append(0.0)
            continue
        if use_wn:
            scores.append(float(nltk_meteor_score(r_toks, p_tok)))
        else:
            scores.append(max(meteor_lite_score(p_tok, r) for r in r_toks))

    return float(sum(scores) / len(scores)) if scores else 0.0


# ── RadFact judge configuration (local vLLM or the real OpenAI API) ────

def _radfact_prompt_revision() -> str:
    """
    Which generation of radfact_lite's toothfairy prompts is installed.

    Upstream (AImageLab-zip/radfact_lite) rewrote the toothfairy parse,
    entailment and filter prompts on 2026-08-09 and renamed the filter module
    negative_filter -> finding_filter in the same series of commits. That
    rename is the cheapest reliable marker: scores from the two generations
    are not comparable, so record which one a run used. PyPI still ships the
    pre-rewrite build, so "pip install radfact-lite" alone yields "legacy".
    """
    try:
        import radfact_lite  # noqa: F401
        import importlib.util
        if importlib.util.find_spec("radfact_lite.finding_filter") is not None:
            return "2026-08-09+"
        return "legacy"
    except Exception:
        return "unknown"



# Reasoning models (o-series, gpt-5) reject `temperature=0`, which the
# installed radfact_lite hardcodes in clients.py -- every call would 400. Warn
# at config time rather than after the first batch dies. Upstream fixed this on
# 2026-08-09 (clients.py now probes which sampling params a model rejects and
# retries without them), so this warning is a no-op once _radfact_prompt_revision()
# reports "2026-08-09+" -- harmless to leave, since it only prints.
_TEMPERATURE_UNSUPPORTED_PREFIXES = ("o1", "o3", "o4", "gpt-5")


class JudgeConfig:
    """
    Everything needed to build radfact_lite's ModelConfig, plus a label for
    the run artifacts. Both backends use radfact_lite's provider="openai"
    client -- vLLM only differs by pointing base_url at the local server
    and using a dummy API key.
    """

    def __init__(self, backend: str, model: str, base_url: Optional[str],
                 api_key_env_var: str, filter_normal_findings: bool = True) -> None:
        self.backend = backend
        self.model = model
        self.base_url = base_url
        self.api_key_env_var = api_key_env_var
        # Drop normal/negative phrases before entailment, so the score is
        # carried by actual findings rather than by boilerplate both reports
        # happen to share. Same judge model does the filtering.
        self.filter_normal_findings = filter_normal_findings

    @classmethod
    def from_args(cls, args) -> "JudgeConfig":
        if args.judge_backend == "openai":
            cfg = cls("openai", args.openai_model, args.openai_base_url or None,
                      args.openai_api_key_env, args.filter_normal_findings)
            if not os.environ.get(cfg.api_key_env_var):
                print(f"[FAIL] --judge-backend openai requires ${cfg.api_key_env_var} to be set.",
                      file=sys.stderr)
                sys.exit(1)
            if cfg.model.lower().startswith(_TEMPERATURE_UNSUPPORTED_PREFIXES):
                print(f"[WARN] Judge model '{cfg.model}' is a reasoning model; radfact_lite "
                      f"sends temperature=0, which such models reject. Expect every call to "
                      f"fail -- use a gpt-4o/gpt-4.1 class model instead.", file=sys.stderr)
            return cfg
        # vLLM: OpenAI-compatible server, key is never checked by vLLM.
        os.environ.setdefault(args.vllm_api_key_env, "not-needed-for-vllm")
        return cls("vllm", args.model, args.vllm_url, args.vllm_api_key_env,
                   args.filter_normal_findings)

    def build_model_config(self):
        from radfact_lite import ModelConfig
        return ModelConfig(
            model=self.model,
            provider="openai",
            api_key_env_var=self.api_key_env_var,
            base_url=self.base_url,
            timeout=float(os.getenv("RADFACT_TIMEOUT", "120")),
            max_retries=int(os.getenv("RADFACT_MAX_RETRIES", "2")),
        )

    def describe(self) -> str:
        target = self.base_url or "https://api.openai.com/v1 (default)"
        return f"backend={self.backend} model={self.model} endpoint={target}"

    def as_metadata(self) -> dict:
        """Provenance recorded into summary.json / official_ranking_*.json."""
        return {
            "judge_backend": self.backend,
            "judge_model": self.model,
            "judge_base_url": self.base_url,
            "filter_normal_findings": self.filter_normal_findings,
            # Which radfact_lite tree produced these numbers. The toothfairy
            # prompts were rewritten upstream on 2026-08-09 and the normal-
            # finding filter prompt with them, so scores are NOT comparable
            # across this value.
            "radfact_lite_prompts": _radfact_prompt_revision(),
            # Kept for backward compatibility with existing result files:
            # older runs recorded vllm_url/model at the top level.
            "vllm_url": self.base_url if self.backend == "vllm" else None,
            "model": self.model,
        }


# ── RadFact (via radfact_lite) ─────────────────────────────────────────

RADFACT_FIELDS_LOGGED = False  # print available per-case RadFact fields once


def compute_radfact_batch(batch_cases: List[Tuple[str, str, str]],
                          judge: JudgeConfig) -> Optional[dict]:
    """
    Run RadFact on ONE batch of cases. Returns {"results": [...]} keyed per
    case (each with logical_precision/recall/f1, plus whatever other fields
    radfact_lite's per-case object exposes), or None if radfact_lite isn't
    installed / the call fails outright.
    """
    global RADFACT_FIELDS_LOGGED
    try:
        from radfact_lite import PipelineModels, RadFactLitePipeline, ReportType
    except ImportError:
        print("[WARN] radfact_lite not installed (pip install radfact_lite). Skipping RadFact.",
              file=sys.stderr)
        return None

    model_config = judge.build_model_config()

    filtering_model = model_config if judge.filter_normal_findings else None

    pipeline = RadFactLitePipeline(
        models=PipelineModels(parse_model=model_config, entailment_model=model_config,
                              filtering_model=filtering_model),
        report_type=ReportType.TOOTHFAIRY,
    )

    # RadFact has no multi-reference mode, so it always judges against the
    # PRIMARY reference even when --multi-reference is on. Only the n-gram
    # metrics (BLEU/METEOR) consume the extra references.
    candidates_by_id = {case_id: candidate for case_id, candidate, _ in batch_cases}
    references_by_id = {case_id: _as_reference_list(refs)[0]
                        for case_id, _, refs in batch_cases}

    # The normal-finding filter kwarg was renamed upstream (2026-08-09):
    # filter_negatives= -> remove_normal_findings=. Passing the wrong one is a
    # TypeError that the except below would swallow into "RadFact skipped,
    # Clinical Score 0.0" -- so pick the name this installed version actually
    # accepts instead of pinning to one.
    import inspect
    _filter_kwarg = ("remove_normal_findings"
                     if "remove_normal_findings" in
                     inspect.signature(pipeline.compute_radfact).parameters
                     else "filter_negatives")

    try:
        _aggregate, per_case = pipeline.compute_radfact(
            candidates_by_id=candidates_by_id,
            references_by_id=references_by_id,
            is_narrative_text=True,
            **{_filter_kwarg: judge.filter_normal_findings},
        )
    except Exception as e:
        print(f"[WARN] RadFact computation failed for this batch: {e}", file=sys.stderr)
        return None

    from dataclasses import asdict
    results = [asdict(r) for r in per_case]

    # One-time debug print: show every field radfact_lite's per-case object
    # actually exposes (e.g. phrase-level entailment lists, box P/R for
    # grounded reports, etc.) -- everything below only *uses* a few of
    # these, so this makes the rest discoverable instead of silently
    # thrown away. See --radfact-detail-out to persist all of it.
    if not RADFACT_FIELDS_LOGGED and results:
        print(f"[INFO] RadFact per-case object fields: {sorted(results[0].keys())}",
              file=sys.stderr)
        RADFACT_FIELDS_LOGGED = True

    return {"results": results}


# ── Case discovery & report loading ─────────────────────────────────────

def discover_cases(synth_dir: Path, reports_dir: Path) -> List[str]:
    """Find case IDs present in both synthesized reports and reference reports."""
    synth_cases = {p.stem for p in synth_dir.glob("*.txt")}
    report_cases = set()
    for p in reports_dir.glob("*.txt"):
        stem = p.stem
        parts = stem.rsplit("_", 1)
        if len(parts) == 2 and parts[1].isdigit():
            report_cases.add(parts[0])
        else:
            report_cases.add(stem)
    return sorted(synth_cases & report_cases)


def load_cases(synth_dir: Path, reports_dir: Path, case_ids: List[str],
               multi_reference: bool = False) -> List[Tuple[str, str, List[str]]]:
    """
    Read pre-synthesized candidate reports (.txt) and reference reports.
    Returns [(case_id, candidate_text, [reference_text, ...]), ...],
    skipping (with a warning) any case missing either file.

    The reference element is ALWAYS a list. With multi_reference=False it
    holds exactly one item -- the primary reference -- so scoring is
    bit-for-bit what it was before this parameter existed. With
    multi_reference=True it holds every radiologist's report for the case.
    """
    cases = []
    for case_id in case_ids:
        # Candidate: pre-synthesized .txt report
        synth_path = synth_dir / f"{case_id}.txt"
        if not synth_path.exists():
            print(f"[SKIP] {case_id}: no synthesized report found in {synth_dir}",
                  file=sys.stderr)
            continue
        candidate_text = synth_path.read_text(encoding="utf-8", errors="replace").strip()

        # Reference(s): ground-truth radiologist report(s)
        ref_paths = find_all_reference_reports(reports_dir, case_id)
        if not ref_paths:
            print(f"[SKIP] {case_id}: no reference report found in {reports_dir}",
                  file=sys.stderr)
            continue
        if not multi_reference:
            ref_paths = ref_paths[:1]
        reference_texts = [p.read_text(encoding="utf-8", errors="replace").strip()
                           for p in ref_paths]
        reference_texts = [t for t in reference_texts if t]
        if not reference_texts:
            print(f"[SKIP] {case_id}: reference report(s) empty in {reports_dir}",
                  file=sys.stderr)
            continue

        cases.append((case_id, candidate_text, reference_texts))
    return cases


# ── Incremental results file ────────────────────────────────────────────

def load_existing_rows(results_path: Path) -> Dict[str, dict]:
    """Read already-written per-case rows (for --resume), keyed by case_id."""
    if not results_path.exists():
        return {}
    rows = {}
    with open(results_path) as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                row = json.loads(line)
                rows[row["case_id"]] = row
            except json.JSONDecodeError:
                continue
    return rows


def rotate_stale_file(path: Path) -> None:
    """
    Move an existing incremental .jsonl aside when starting a NON-resume run.

    Rows are always appended, and prior rows are only read back under --resume,
    so re-running into the same --out-dir without --resume would otherwise leave
    duplicate case rows in the file (the aggregate stays correct -- it is built
    from the in-memory dict -- but the per-case file becomes unusable).
    """
    if not path.exists():
        return
    backup = path.with_suffix(path.suffix + ".prev")
    path.replace(backup)
    print(f"[INFO] Non-resume run: moved existing {path.name} -> {backup.name}",
          file=sys.stderr)


def append_rows(results_path: Path, rows: List[dict]) -> None:
    """Append rows to results.jsonl, flushing immediately so they survive a crash."""
    with open(results_path, "a") as f:
        for row in rows:
            f.write(json.dumps(row) + "\n")
            f.flush()
            os.fsync(f.fileno())


def mean_sd(values: List[float]) -> Tuple[float, float]:
    """Mean and sample standard deviation (ddof=1) of a list of per-case
    values. SD is 0.0 for fewer than 2 values (stdev() would otherwise
    raise), which is the right behavior for a single-case batch/run."""
    clean = [v for v in values if v is not None]
    if not clean:
        return 0.0, 0.0
    m = statistics.mean(clean)
    sd = statistics.stdev(clean) if len(clean) >= 2 else 0.0
    return float(m), float(sd)


def compute_per_case_stats(case_ids: List[str], rows_by_id: Dict[str, dict]) -> dict:
    """Per-case mean +/- sd for every scored metric, computed directly from
    the per-case rows already stored in rows_by_id (each row already holds
    its own single-case bleu_4/meteor/logical_*/captioning_score/
    clinical_score/final_score -- no re-scoring needed here).

    NOTE: this is DIFFERENT from compute_aggregate()'s bleu_4/meteor, which
    are corpus-level (matching the official challenge metric definition).
    Corpus BLEU-4 in particular is NOT the mean of per-case BLEU-4 scores --
    it's computed jointly across all candidate/reference pairs. Both are
    reported side by side rather than one replacing the other.
    """
    rows = [rows_by_id[cid] for cid in case_ids if cid in rows_by_id]
    if not rows:
        return {}

    def stat_for(key):
        m, sd = mean_sd([r.get(key) for r in rows])
        return {"mean": m, "sd": sd}

    stats = {
        "bleu_4": stat_for("bleu_4"),
        "meteor": stat_for("meteor"),
        "captioning_score": stat_for("captioning_score"),
        "clinical_score": stat_for("clinical_score"),
        "final_score": stat_for("final_score"),
    }
    radfact_rows = [r for r in rows if r.get("logical_f1") is not None]
    if radfact_rows:
        stats["logical_precision"] = stat_for("logical_precision")
        stats["logical_recall"] = stat_for("logical_recall")
        stats["logical_f1"] = stat_for("logical_f1")
    return stats


def compute_aggregate(all_case_ids: List[str], rows_by_id: Dict[str, dict],
                      synth_dir: Path, reports_dir: Path,
                      multi_reference: bool = False) -> dict:
    """
    Recompute the FULL aggregate (true corpus-level BLEU-4, mean METEOR,
    RadFact aggregate P/R/F1, Final Score) from every row processed so far
    (this run plus any resumed prior rows). Corpus BLEU/METEOR need the raw
    text, which we re-read from disk rather than duplicating in
    results.jsonl (keeps that file lean).

    Also attaches "per_case_stats": mean +/- sd across the individual
    per-case rows for every metric (see compute_per_case_stats) -- this is
    the +/- sd view; it sits alongside, not instead of, the official
    corpus-level numbers above.
    """
    if not all_case_ids:
        return {"num_cases": 0, "bleu_4": 0.0, "meteor": 0.0, "captioning_score": 0.0,
                "radfact_enabled": False, "clinical_score": 0.0, "final_score": 0.0,
                "per_case_stats": {}}

    texts = load_cases(synth_dir, reports_dir, all_case_ids, multi_reference)
    predictions = [t[1] for t in texts]
    references = [t[2] for t in texts]

    bleu4_agg = bleu_4_local(predictions, references)
    meteor_agg = meteor_batch(predictions, references)
    captioning = (bleu4_agg + meteor_agg) / 2.0

    radfact_rows = [rows_by_id[cid] for cid in all_case_ids
                    if cid in rows_by_id and rows_by_id[cid].get("logical_f1") is not None]
    if radfact_rows:
        mean_p = sum(r["logical_precision"] for r in radfact_rows) / len(radfact_rows)
        mean_r = sum(r["logical_recall"] for r in radfact_rows) / len(radfact_rows)
        clinical = (2 * mean_p * mean_r / (mean_p + mean_r)) if (mean_p + mean_r) else 0.0
        radfact_enabled = True
    else:
        mean_p = mean_r = None
        clinical = 0.0
        radfact_enabled = False

    return {
        "num_cases": len(texts),
        "bleu_4": bleu4_agg,
        "meteor": meteor_agg,
        "captioning_score": captioning,
        "radfact_enabled": radfact_enabled,
        "logical_precision": mean_p,
        "logical_recall": mean_r,
        "clinical_score": clinical,
        "final_score": 0.8 * clinical + 0.2 * captioning,
        "per_case_stats": compute_per_case_stats(all_case_ids, rows_by_id),
    }


